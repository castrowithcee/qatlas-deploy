package engine

import (
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"syscall"
	"time"
	"unicode"
)

const (
	maxLogBytes = 256 << 10
	maxLogLine  = 2 << 10
	logExt      = ".log"
)

// ErrLogFull means a run log has reached its size bound and takes no further entry.
var ErrLogFull = errors.New("run log is full")

// ErrNoSuchRun means the run id is malformed or has no log.
var ErrNoSuchRun = errors.New("no such run")

// Log is the run log a Deployer writes its steps to. Every text passes the redactor, is reduced to printable
// characters and bounded in line and total size, so a deployer cannot leak a registered secret or flood the
// state directory.
type Log struct {
	mu       sync.Mutex
	w        io.WriteCloser
	redact   func(string) string
	now      func() time.Time
	written  int
	overflow bool
}

// Step starts a named step of the run.
func (l *Log) Step(name string) { l.line("step", name) }

// Printf adds detail to the current step.
func (l *Log) Printf(format string, args ...any) { l.line("info", fmt.Sprintf(format, args...)) }

// line writes one entry; a nil Log discards it.
func (l *Log) line(kind, text string) {
	if l == nil {
		return
	}
	l.mu.Lock()
	defer l.mu.Unlock()
	if l.w == nil || l.overflow {
		return
	}
	if l.redact != nil {
		text = l.redact(text)
	}
	stamp := l.now().UTC().Format(time.RFC3339)
	for _, part := range strings.Split(text, "\n") {
		out := stamp + " " + kind + " " + printableLine(part) + "\n"
		if l.written+len(out) > maxLogBytes {
			l.overflow = true
			_, _ = io.WriteString(l.w, stamp+" info log truncated\n")
			return
		}
		n, err := io.WriteString(l.w, out)
		l.written += n
		if err != nil {
			l.overflow = true
			return
		}
	}
}

func (l *Log) close() {
	l.mu.Lock()
	defer l.mu.Unlock()
	if l.w != nil {
		_ = l.w.Close()
		l.w = nil
	}
}

func printableLine(s string) string {
	var b strings.Builder
	n := 0
	for _, r := range s {
		if n == maxLogLine {
			b.WriteString("...")
			break
		}
		if unicode.IsPrint(r) {
			b.WriteRune(r)
		} else {
			b.WriteByte(' ')
		}
		n++
	}
	return b.String()
}

// logStore keeps the run logs below one directory. Only ids generated by the engine name files.
type logStore struct{ dir string }

func (s logStore) path(id string) (string, error) {
	if !runIDRe.MatchString(id) {
		return "", ErrNoSuchRun
	}
	return filepath.Join(s.dir, id+logExt), nil
}

// create opens a new log for id; an existing file is never reused.
func (s logStore) create(id string) (io.WriteCloser, error) {
	p, err := s.path(id)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(s.dir, 0o700); err != nil {
		return nil, err
	}
	return os.OpenFile(p, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
}

func (s logStore) read(id string) (string, error) {
	p, err := s.path(id)
	if err != nil {
		return "", err
	}
	fi, err := os.Lstat(p)
	if errors.Is(err, fs.ErrNotExist) || (err == nil && !fi.Mode().IsRegular()) {
		return "", ErrNoSuchRun
	}
	if err != nil {
		return "", err
	}
	f, err := os.Open(p)
	if err != nil {
		return "", err
	}
	defer f.Close()
	data, err := io.ReadAll(io.LimitReader(f, maxLogBytes+maxLogLine))
	return string(data), err
}

func (s logStore) remove(ids ...string) {
	for _, id := range ids {
		if p, err := s.path(id); err == nil {
			_ = os.Remove(p)
		}
	}
}

// appendLine adds one entry to the log of a finished run. It never creates a file, never follows a symlink and
// never grows the log beyond maxLogBytes. A log that retention removed meanwhile is ErrNoSuchRun.
func (s logStore) appendLine(id, stamp, kind, text string) error {
	p, err := s.path(id)
	if err != nil {
		return err
	}
	fi, err := os.Lstat(p)
	if errors.Is(err, fs.ErrNotExist) || (err == nil && !fi.Mode().IsRegular()) {
		return ErrNoSuchRun
	}
	if err != nil {
		return err
	}
	f, err := os.OpenFile(p, os.O_WRONLY|os.O_APPEND|syscall.O_NOFOLLOW, 0)
	if errors.Is(err, fs.ErrNotExist) || errors.Is(err, syscall.ELOOP) {
		return ErrNoSuchRun
	}
	if err != nil {
		return err
	}
	defer f.Close()
	if fi, err = f.Stat(); err != nil {
		return err
	}
	if !fi.Mode().IsRegular() {
		return ErrNoSuchRun
	}
	var b strings.Builder
	for _, part := range strings.Split(text, "\n") {
		b.WriteString(stamp + " " + kind + " " + printableLine(part) + "\n")
	}
	if fi.Size()+int64(b.Len()) > maxLogBytes {
		return ErrLogFull
	}
	_, err = io.WriteString(f, b.String())
	return err
}
